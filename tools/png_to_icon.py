#!/usr/bin/env python3
"""
tools/png_to_icon.py

Turns a 32x32 PNG into a C header holding one VIGIL app icon, ready to
#include from an app and point app_t.icon at

Needs pillow:
    pip install pillow

Usage:
    python tools/png_to_icon.py <png> <output header> <symbol name>
Example:
    python tools/png_to_icon.py apps/hello/icon.png apps/hello/hello_icon.h hello_icon
"""

import sys
from typing import NoReturn

from PIL import Image

ICON_SIZE = 32
PER_LINE = 8


def fail(message: str) -> NoReturn:
    print('png_to_icon: ' + message, file=sys.stderr)
    sys.exit(1)


def load_pixels(png_path: str) -> list[int]:
    try:
        image = Image.open(png_path).convert('RGBA')
    except OSError as err:
        fail('cannot read %s: %s' % (png_path, err))

    if image.size != (ICON_SIZE, ICON_SIZE):
        fail('%s is %dx%d, icons must be exactly %dx%d'
             % (png_path, image.width, image.height, ICON_SIZE, ICON_SIZE))

    pixels: list[int] = []
    for y in range(ICON_SIZE):
        for x in range(ICON_SIZE):
            r, g, b, a = image.getpixel((x, y))
            pixels.append((a << 24) | (r << 16) | (g << 8) | b)
    return pixels


def write_header(path: str, symbol: str, pixels: list[int]) -> None:
    guard = symbol.upper() + '_H'
    lines = [
        '// generated by tools/png_to_icon.py, do not edit by hand',
        '',
        '#ifndef %s' % guard,
        '#define %s' % guard,
        '#include <stdint.h>',
        '',
        'static const uint32_t %s[%d * %d] = {' % (symbol, ICON_SIZE, ICON_SIZE),
    ]

    for i in range(0, len(pixels), PER_LINE):
        chunk = pixels[i:i + PER_LINE]
        lines.append('    ' + ', '.join('0x%08x' % p for p in chunk) + ',')

    lines += ['};', '', '#endif', '']

    with open(path, 'w', newline='\n') as out:
        out.write('\n'.join(lines))


if __name__ == '__main__':
    if len(sys.argv) != 4:
        fail('usage: png_to_icon.py <png> <output header> <symbol name>')
    if not sys.argv[3].isidentifier():
        fail("'%s' is not a valid C name" % sys.argv[3])

    icon = load_pixels(sys.argv[1])
    write_header(sys.argv[2], sys.argv[3], icon)
    print('wrote %s (%d pixels)' % (sys.argv[2], len(icon)))
